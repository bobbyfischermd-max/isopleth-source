import type { AtlasNode, BasinId, DriverId, Drivers } from "@/lib/model/types";
import { DRIVER_IDS } from "@/lib/model/types";

function D(m: number, r: number, h: number, i: number, c: number, g: number): Drivers {
  return { meteo: m, resources: r, human: h, infra: i, corporate: c, institutions: g };
}

function row(
  id: string,
  name: string,
  basin: BasinId,
  lat: number,
  lon: number,
  b: number[],
  a: number[],
  s: number[],
  assets: string,
  control: string,
  mexicoTest = false,
): AtlasNode {
  const base = {} as Drivers;
  const slope = {} as Drivers;
  DRIVER_IDS.forEach((k, i) => {
    base[k] = b[i] ?? 0;
    slope[k] = s[i] ?? 0;
  });
  return {
    id,
    name,
    basin,
    lat,
    lon,
    base,
    solar: a[0] ?? 0,
    water: a[1] ?? 0,
    agri: a[2] ?? 0,
    minerals: a[3] ?? 0,
    hydrocarb: a[4] ?? 0,
    coast: a[5] ?? 0,
    strategic: a[6] ?? 0,
    skills: a[7] ?? 0,
    pop: a[8] ?? 0,
    extract: a[9] ?? 0,
    slope,
    assets,
    control,
    mexicoTest,
  };
}

